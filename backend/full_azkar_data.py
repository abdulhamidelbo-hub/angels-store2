def convert_to_evening(morning_items):
    """تحويل أذكار الصباح إلى أذكار المساء"""
    evening_items = []
    for item in morning_items:
        text = item["arabic"]
        # استبدال الصيغ
        text = text.replace("أَصْبَحْنَا", "أَمْسَيْنَا")
        text = text.replace("أَصْبَحَ", "أَمْسَى")
        text = text.replace("أَصْبَحْتُ", "أَمْسَيْتُ")
        text = text.replace("الصَّبَاح", "الْمَسَاء")
        text = text.replace("الصباح", "المساء")
        text = text.replace("هَذَا الْيَوْمِ", "هَذِهِ اللَّيْلَةِ")
        text = text.replace("هذا اليوم", "هذه الليلة")
        text = text.replace("النُّشُورُ", "الْمَصِيرُ")
        new_item = item.copy()
        new_item["arabic"] = text
        evening_items.append(new_item)
    return evening_items


