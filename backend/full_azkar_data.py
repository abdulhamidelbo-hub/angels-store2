def generate_transliteration(arabic_text):
    """توليد النطق بالحروف اللاتينية (مبسط)"""
    # قاموس مبسط للتحويل
    transliterations = {
        "سُبْحَانَ اللَّهِ": "Subhan Allah",
        "الْحَمْدُ لِلَّهِ": "Alhamdulillah",
        "اللَّهُ أَكْبَرُ": "Allahu Akbar",
        "لا إِلَهَ إِلَّا اللَّهُ": "La ilaha illallah",
        "أَسْتَغْفِرُ اللَّهَ": "Astaghfirullah",
        "لا حَوْلَ وَلا قُوَّةَ إِلاَّ بِاللَّهِ": "La hawla wa la quwwata illa billah",
        "بِسْمِ اللَّهِ": "Bismillah",
        "اللَّهُمَّ": "Allahumma",
    }
    
    for ar, en in transliterations.items():
        if ar in arabic_text:
            return en
    
    return None


